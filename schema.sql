-- Run in Supabase SQL Editor.
create table if not exists public.profile (
  id bigint generated by default as identity primary key,
  name text not null,
  title text,
  about text,
  email text,
  whatsapp text,
  linkedin text,
  instagram text,
  youtube text,
  updated_at timestamptz default now()
);

create table if not exists public.education (
  id text primary key,
  title text not null,
  category text,
  description text,
  details jsonb default '[]'::jsonb
);

create table if not exists public.experiences (
  id text primary key,
  title text not null,
  category text,
  description text,
  details jsonb default '[]'::jsonb
);

create table if not exists public.projects (
  id text primary key,
  title text not null,
  category text,
  description text,
  details jsonb default '[]'::jsonb,
  tags jsonb default '[]'::jsonb,
  link text
);

create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  group_name text not null,
  items jsonb default '[]'::jsonb
);

create table if not exists public.certificates (
  id text primary key,
  title text not null,
  category text,
  description text,
  details jsonb default '[]'::jsonb,
  file_url text
);

create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  image_url text,
  category text
);

create table if not exists public.game_zones (
  id text primary key,
  label text not null,
  x numeric not null default 0,
  y numeric not null default 0,
  color text
);

create table if not exists public.game_objects (
  id text primary key,
  zone_id text references public.game_zones(id) on delete cascade,
  label text not null,
  x numeric not null default 0,
  y numeric not null default 0,
  interaction_type text,
  content_id text
);

create table if not exists public.achievements (
  id text primary key,
  title text not null,
  description text,
  icon text,
  points integer default 0
);

-- Public read access for portfolio content. Writes remain disabled for anon users.
alter table public.profile enable row level security;
alter table public.education enable row level security;
alter table public.experiences enable row level security;
alter table public.projects enable row level security;
alter table public.skills enable row level security;
alter table public.certificates enable row level security;
alter table public.gallery enable row level security;
alter table public.game_zones enable row level security;
alter table public.game_objects enable row level security;
alter table public.achievements enable row level security;

do $$
declare t text;
begin
  foreach t in array array['profile','education','experiences','projects','skills','certificates','gallery','game_zones','game_objects','achievements']
  loop
    execute format('drop policy if exists "Public can read %I" on public.%I', t, t);
    execute format('create policy "Public can read %I" on public.%I for select to anon, authenticated using (true)', t, t);
  end loop;
end $$;

-- Storage bucket for public portfolio assets.
insert into storage.buckets (id, name, public)
values ('portfolio-assets', 'portfolio-assets', true)
on conflict (id) do nothing;

create policy if not exists "Public can view portfolio assets"
on storage.objects for select to anon, authenticated
using (bucket_id = 'portfolio-assets');
